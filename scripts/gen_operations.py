"""Prepares generation. Needs PyYAML.

- build/openapi.prep.yaml                  : the spec without webhook callbacks (server-to-customer, not part of the SDK).
- src/Sitewarm.Sdk/Operations.cs           : operationId -> method/path/idempotency table.

Then run the type generator: see scripts/generate.sh.
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
spec = yaml.safe_load((ROOT / "openapi" / "openapi.yaml").read_text())

prep = yaml.safe_load(yaml.safe_dump(spec))
prep.pop("webhooks", None)
prep.get("components", {}).pop("callbacks", None)
for item in prep["paths"].values():
    for op in item.values():
        if isinstance(op, dict):
            op.pop("callbacks", None)
(ROOT / "build").mkdir(exist_ok=True)
(ROOT / "build" / "openapi.prep.yaml").write_text(yaml.safe_dump(prep, sort_keys=False))

rows = []
for path, item in spec["paths"].items():
    for method in ("get", "put", "post", "patch", "delete"):
        op = item.get(method)
        if not op:
            continue
        refs = [p.get("$ref", "") for p in [*item.get("parameters", []), *op.get("parameters", [])]]
        idem = next((r for r in refs if r.endswith("/IdempotencyKey") or r.endswith("/IdempotencyKeyRequired")), None)
        kind = "None" if not idem else ("Required" if idem.endswith("Required") else "Optional")
        rows.append((op["operationId"], method.upper(), path, kind))
rows.sort()

lines = "\n".join(f'        ["{i}"] = new("{m}", "{p}", Idempotency.{k}),' for i, m, p, k in rows)
out = ROOT / "src" / "Sitewarm.Sdk"
out.mkdir(parents=True, exist_ok=True)
(out / "Operations.cs").write_text(
    "// GENERATED by scripts/gen_operations.py from openapi/openapi.yaml. Do not edit.\n"
    "using System.Collections.Generic;\n\n"
    "namespace Sitewarm.Sdk;\n\n"
    "/// <summary>Whether an operation accepts or requires an Idempotency-Key.</summary>\n"
    "internal enum Idempotency { None, Optional, Required }\n\n"
    "internal sealed record Operation(string Method, string Path, Idempotency Idempotency);\n\n"
    "/// <summary>operationId to method, path and idempotency support.</summary>\n"
    "internal static class Operations\n{\n"
    "    internal static readonly IReadOnlyDictionary<string, Operation> Table = new Dictionary<string, Operation>\n    {\n"
    f"{lines}\n"
    "    };\n}\n"
)
print(f"generated {len(rows)} operations")
